// Command plugingen 把「仓库外第三方插件」的接入从手改两处变成扫目录 + 代码生成。
//
// 它替人做两件事，都幂等：
//
//  1. 生成 cmd/app/plugins_gen.go —— 一串 _ "外部 module" 的 blank import
//  2. 需要时把 module 接进 go.mod —— go mod edit -require / -replace（指向绝对路径）
//
// 用法：
//
//	go run ./cmd/plugingen -config tmp/ui-plugins.json -dry-run   # 先看计划
//	go run ./cmd/plugingen -config tmp/ui-plugins.json
package main

import (
	"bytes"
	"encoding/json"
	"flag"
	"fmt"
	"go/format"
	"os"
	"os/exec"
	"path/filepath"
	"strings"

	"github.com/MYCF711/dsh-ui/internal/uiplugins"
)

func main() {
	cfgPath := flag.String("config", "", "插件配置文件（ui-plugins.json）；只读它的 dirs")
	out := flag.String("o", "cmd/app/plugins_gen.go", "生成文件路径")
	dry := flag.Bool("dry-run", false, "只打印计划：不写文件、不改 go.mod")
	modDir := flag.String("mod", "", "go.mod 所在目录（默认从生成文件所在目录向上找）")
	flag.Parse()

	if err := run(*cfgPath, *out, *modDir, *dry); err != nil {
		fmt.Fprintf(os.Stderr, "plugingen: %v\n", err)
		os.Exit(1)
	}
}

func run(cfgPath, outPath, modDirFlag string, dry bool) error {
	header("plugingen")
	printf("配置      %s\n", orDash(cfgPath))

	cfg, err := uiplugins.ReadConfig(cfgPath)
	if err != nil {
		return err
	}
	dirs, err := cfg.ResolveDirs(cfgPath)
	if err != nil {
		return err
	}
	// 目录不存在一律报错（一次列全），绝不静默跳过：
	// 配置里写了就说明用户认为它在；跳过等于把打错的路径变成一个谜。
	if len(dirs) > 0 {
		base, berr := uiplugins.ConfigDir(cfgPath)
		if berr != nil {
			return berr
		}
		if missing := missingDirs(dirs); len(missing) > 0 {
			return fmt.Errorf("配置里列的插件目录不存在或不是目录（%d 个）:\n  %s\n"+
				"（dirs 里每一项都相对配置文件所在目录解析：%s）",
				len(missing), strings.Join(missing, "\n  "), base)
		}
	}

	// ── 1. 扫描 ──
	var plugins []Plugin
	byModule := map[string]string{} // module -> 目录（查重用）
	if len(dirs) == 0 {
		printf("插件目录  （dirs 为空：不接任何外部插件）\n")
	}
	for _, dir := range dirs {
		printf("插件目录  %s\n", dir)
		found, skipped, err := scanRoot(dir)
		if err != nil {
			return err
		}
		for _, s := range skipped {
			printf("  跳过 %-16s %s\n", s.Name, s.Reason)
		}
		for _, p := range found {
			if prev, dup := byModule[p.Module]; dup {
				return fmt.Errorf("module %s 同时出现在两个插件目录里:\n  %s\n  %s",
					p.Module, prev, p.Dir)
			}
			byModule[p.Module] = p.Dir
			plugins = append(plugins, p)
			printf("  + %-16s module=%s package=%s", filepath.Base(p.Dir), p.Module, p.Package)
			if p.Manifest {
				printf("  (plugin.json)")
			} else {
				printf("  (go.mod)")
			}
			printf("\n")
			if p.Warn != "" {
				printf("    注意: %s\n", p.Warn)
			}
		}
	}
	if len(dirs) > 0 && len(plugins) == 0 {
		printf("  （这些目录里没有认定出插件；认定规则见 docs/plugin-api.md §13）\n")
	}

	mods := make([]string, 0, len(plugins))
	for _, p := range plugins {
		mods = append(mods, p.Module)
	}

	// ── 2. 生成 ──
	absOut, err := filepath.Abs(outPath)
	if err != nil {
		return fmt.Errorf("解析生成文件路径 %s 失败: %w", outPath, err)
	}
	src, err := render(mods)
	if err != nil {
		return err
	}
	printf("生成文件  %s\n", outPath)

	// ── 3. go.mod ──
	modRoot, err := resolveModRoot(absOut, modDirFlag)
	if err != nil {
		return err
	}
	printf("go.mod    %s\n", filepath.Join(modRoot, "go.mod"))
	modLines, modErr := ensureModules(modRoot, plugins, dry)
	if modErr != nil {
		return modErr
	}
	for _, l := range modLines {
		printRaw("%s\n", l)
	}

	if dry {
		printRaw("\n--- 生成的 %s（dry-run，未写入）---\n", outPath)
		printRaw("%s", src)
		printRaw("\n结果: dry-run，什么都没改\n")
		return nil
	}

	changed, err := writeFile(absOut, src)
	if err != nil {
		return err
	}
	if changed {
		printf("写入      %s（%d 字节，LF）\n", outPath, len(src))
	} else {
		printf("写入      %s（内容相同，未重写）\n", outPath)
	}
	printf("\n结果: 外部插件 %d 个", len(plugins))
	if len(mods) == 0 {
		printf("（空 import 块，能编译）")
	}
	printf("\n")
	printf("下一步: CGO_ENABLED=0 go build ./cmd/app（重新编译才会带上这些 module）\n")
	return nil
}

// ── 生成 ──

// render 产出 go/format 过的源码：行尾是 LF，gofmt -l 一定是干净的。
func render(mods []string) ([]byte, error) {
	var b strings.Builder
	b.WriteString("// Code generated by cmd/plugingen. DO NOT EDIT.\n")
	b.WriteString("package main\n\n")
	if len(mods) == 0 {
		// 空 import 块：语法合法、能编译，且一眼看出「这里本来该有东西」。
		b.WriteString("import ()\n")
	} else {
		b.WriteString("import (\n")
		for _, m := range mods {
			fmt.Fprintf(&b, "\t_ %q\n", m)
		}
		b.WriteString(")\n")
	}
	src, err := format.Source([]byte(b.String()))
	if err != nil {
		return nil, fmt.Errorf("生成的源码不合法（plugingen 自己的 bug）: %w", err)
	}
	return src, nil
}

// writeFile 只在内容不同时落盘（内容一样就保持 mtime，构建缓存不白掉）。
func writeFile(path string, data []byte) (bool, error) {
	if old, err := os.ReadFile(path); err == nil && bytes.Equal(old, data) {
		return false, nil
	}
	if err := os.MkdirAll(filepath.Dir(path), 0o755); err != nil {
		return false, fmt.Errorf("建目录 %s 失败: %w", filepath.Dir(path), err)
	}
	if err := os.WriteFile(path, data, 0o644); err != nil {
		return false, fmt.Errorf("写 %s 失败: %w", path, err)
	}
	return true, nil
}

// ── go.mod ──

// goModInfo 只取 go mod edit -json 里用得到的字段。
type goModInfo struct {
	Module  struct{ Path string }
	Require []struct{ Path, Version string }
	Replace []struct {
		Old struct{ Path, Version string }
		New struct{ Path, Version string }
	}
}

func readModInfo(modRoot string) (*goModInfo, error) {
	bin, err := goBin()
	if err != nil {
		return nil, err
	}
	cmd := exec.Command(bin, "mod", "edit", "-json")
	cmd.Dir = modRoot
	out, err := cmd.Output()
	if err != nil {
		msg := err.Error()
		if ee, ok := err.(*exec.ExitError); ok {
			msg = strings.TrimSpace(string(ee.Stderr))
		}
		return nil, fmt.Errorf("读 %s 失败: %s", filepath.Join(modRoot, "go.mod"), msg)
	}
	var info goModInfo
	if err := json.Unmarshal(out, &info); err != nil {
		return nil, fmt.Errorf("解析 go mod edit -json 输出失败: %w", err)
	}
	return &info, nil
}

// ensureModules 把每个外部 module 接进 go.mod（缺什么补什么，已有的一律不动）。
func ensureModules(modRoot string, plugins []Plugin, dry bool) ([]string, error) {
	if len(plugins) == 0 {
		return []string{"  （没有外部插件，go.mod 不用改）"}, nil
	}
	info, err := readModInfo(modRoot)
	if err != nil {
		return nil, err
	}
	var lines []string
	for _, p := range plugins {
		slashDir := filepath.ToSlash(p.Dir) // go.mod 里一律正斜杠（含空格时 go 会自动加引号）
		lines = append(lines, fmt.Sprintf("  %s", p.Module))

		// require
		reqVersion := ""
		for _, r := range info.Require {
			if r.Path == p.Module {
				reqVersion = r.Version
			}
		}
		if reqVersion != "" {
			lines = append(lines, fmt.Sprintf("    = require 已存在 %s", reqVersion))
		} else if dry {
			lines = append(lines, fmt.Sprintf("    + require %s@v0.0.0（将添加）", p.Module))
		} else {
			if err := goModEdit(modRoot, "-require="+p.Module+"@v0.0.0"); err != nil {
				return nil, err
			}
			lines = append(lines, fmt.Sprintf("    + require %s@v0.0.0（已添加）", p.Module))
		}

		// replace
		cur, found := "", false
		for _, r := range info.Replace {
			if r.Old.Path == p.Module && r.Old.Version == "" {
				cur, found = r.New.Path, true
			}
		}
		switch {
		case found && samePath(modRoot, cur, p.Dir):
			lines = append(lines, fmt.Sprintf("    = replace 已存在 => %s", cur))
		case found:
			// 已有 replace 指向别处：这是用户的决定，不覆盖，只提醒。
			lines = append(lines, fmt.Sprintf("    ! replace 已存在但指向 %s（与扫描目录 %s 不同，保留原值）", cur, slashDir))
		case dry:
			lines = append(lines, fmt.Sprintf("    + replace %s => %s（将添加）", p.Module, slashDir))
		default:
			if err := goModEdit(modRoot, "-replace="+p.Module+"="+slashDir); err != nil {
				return nil, err
			}
			lines = append(lines, fmt.Sprintf("    + replace %s => %s（已添加）", p.Module, slashDir))
		}
	}
	return lines, nil
}

func goModEdit(modRoot, arg string) error {
	bin, err := goBin()
	if err != nil {
		return err
	}
	cmd := exec.Command(bin, "mod", "edit", arg)
	cmd.Dir = modRoot
	var stderr bytes.Buffer
	cmd.Stderr = &stderr
	if err := cmd.Run(); err != nil {
		return fmt.Errorf("go mod edit %s 失败: %s", arg, strings.TrimSpace(stderr.String()))
	}
	return nil
}

func goBin() (string, error) {
	p, err := exec.LookPath("go")
	if err != nil {
		return "", fmt.Errorf("找不到 go 命令（生成器要用 go mod edit 改 go.mod）: %w", err)
	}
	return p, nil
}

// samePath 比较两个路径是不是同一个目录：相对路径按 modRoot 解析，Windows 忽略大小写。
func samePath(modRoot, a, b string) bool {
	norm := func(p string) string {
		if !filepath.IsAbs(p) {
			p = filepath.Join(modRoot, p)
		}
		return filepath.Clean(p)
	}
	return strings.EqualFold(norm(a), norm(b))
}

// ── 路径 ──

// missingDirs 返回不存在的目录（保持原顺序，报错信息里好对）。
func missingDirs(dirs []string) []string {
	var out []string
	for _, d := range dirs {
		st, err := os.Stat(d)
		if err != nil || !st.IsDir() {
			out = append(out, d)
		}
	}
	return out
}

// resolveModRoot：-mod 优先；否则从生成文件所在目录向上找 go.mod，
// 找不到再退回当前工作目录向上找。
func resolveModRoot(absOut, modDirFlag string) (string, error) {
	if modDirFlag != "" {
		root, ok := findModuleRoot(modDirFlag)
		if !ok {
			return "", fmt.Errorf("-mod %s 下（含其祖先）没有 go.mod", modDirFlag)
		}
		return root, nil
	}
	if root, ok := findModuleRoot(filepath.Dir(absOut)); ok {
		return root, nil
	}
	if wd, err := os.Getwd(); err == nil {
		if root, ok := findModuleRoot(wd); ok {
			return root, nil
		}
	}
	return "", fmt.Errorf("找不到 go.mod：从 %s 向上没有找到（用 -mod 指定）", filepath.Dir(absOut))
}

func findModuleRoot(start string) (string, bool) {
	dir, err := filepath.Abs(start)
	if err != nil {
		return "", false
	}
	for {
		if st, err := os.Stat(filepath.Join(dir, "go.mod")); err == nil && !st.IsDir() {
			return dir, true
		}
		parent := filepath.Dir(dir)
		if parent == dir {
			return "", false
		}
		dir = parent
	}
}

// ── 输出 ──

func header(name string) {
	printRaw("== %s ==\n", name)
}

func printf(format string, args ...any) {
	printRaw(format, args...)
}

// printRaw 走 fmt.Fprintf(os.Stdout) 而不是 log：生成器的输出是给人看的计划，
// 不该带时间戳前缀（时间戳留给真正的日志）。
func printRaw(format string, args ...any) {
	fmt.Fprintf(os.Stdout, format, args...)
}

func orDash(s string) string {
	if s == "" {
		return "（空：不读配置）"
	}
	return s
}
